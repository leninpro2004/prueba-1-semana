-- ============================================================
-- Histórico de terreno.prestamo_herramientas  (tabla eliminada el 2026-09-19)
--
-- POR QUÉ SE ELIMINÓ
-- La tabla quedó huérfana en OPUS-13: inventario.asignacion_herramienta la
-- reemplaza y ningún código la consultaba. Además tenía dos defectos que la
-- hacían inservible:
--   1. sku_material era BIGINT contra un material_sku VARCHAR(16), así que
--      nunca pudo referenciar un material de verdad.
--   2. fecha_devolucion era NOT NULL, con lo cual no podía representar un
--      préstamo VIGENTE — justo lo que uno necesita de una tabla de préstamos.
--
-- POR QUÉ SUS 2 FILAS NO SE MIGRARON
-- Ambas tenían sku_material = 1, que no corresponde a ningún material del
-- catálogo. asignacion_herramienta.material_sku es NOT NULL con FK a material,
-- así que insertarlas habría exigido inventar un material — y el catálogo real
-- de herramientas (lentes, taladros, guantes, martillos…) todavía no se cargó.
-- Inventar SKUs ahora se chocaría con ese catálogo después.
--
-- Se conservan acá tal cual estaban, y abajo queda el INSERT listo para cuando
-- existan los SKUs reales. Las observaciones nombran las herramientas, así que
-- se pueden identificar.
-- ============================================================

